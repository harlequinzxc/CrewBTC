test('stations survive switching, reload and project transfer; selected cards pack together', async ({ page, browser }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await uploadPdf(page)
  await page.getByRole('button', { name: 'Station 1', exact: true }).dblclick()
  await page.getByRole('textbox', { name: 'Rename Station 1' }).fill('SIN')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: 'SIN', exact: true })).toBeVisible()
  await textZones(page).first().click()
  await page.getByLabel('Edit card text').fill('SIN SIGNATURE')
  await page.keyboard.press('Escape')
  page.once('dialog', (dialog) => dialog.accept('HND'))
  await page.getByRole('button', { name: 'New station' }).click()
  await expect(page.getByRole('button', { name: 'HND', exact: true })).toHaveAttribute('aria-current', 'page')
  const chooserPromise = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: /add pdfs/i }).first().click()
  await (await chooserPromise).setFiles(pdfFile())
  await expect(textZones(page).first()).toBeVisible({ timeout: 30000 })
  await textZones(page).first().click()
  await page.getByLabel('Edit card text').fill('HND SIGNATURE')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'SIN', exact: true }).click()
  await expect(textZones(page).first()).toContainText('SIN SIGNATURE')
  await page.waitForTimeout(1000)
  await page.reload()
  await expect(textZones(page).first()).toContainText('SIN SIGNATURE', { timeout: 30000 })
  await page.getByRole('button', { name: 'HND', exact: true }).click()
  await expect(textZones(page).first()).toContainText('HND SIGNATURE')
  await openSheetSettings(page)
  await page.getByLabel('Cell width').fill('190')
  await openSheetSettings(page)
  await page.getByLabel('Cell height').fill('200')
  await page.getByRole('button', { name: 'SIN', exact: true }).click()
  await expect(textZones(page).first()).toContainText('SIN SIGNATURE')
  await openSheetSettings(page)
  await page.getByLabel('Cell width').fill('52')
  await openSheetSettings(page)
  await page.getByLabel('Cell height').fill('67')
  await page.getByRole('button', { name: 'HND', exact: true }).click()
  await expect(textZones(page).first()).toContainText('HND SIGNATURE')
  await page.getByRole('button', { name: 'Export PDF' }).click()
  await page.getByRole('menuitem', { name: 'Custom selection' }).click()
  const dialog = page.getByRole('dialog', { name: 'Print selection' })
  const checks = dialog.locator('input[data-print-card]')
  await expect(checks).toHaveCount(4)
  await checks.nth(0).click()
  await checks.nth(3).click({ modifiers: ['Shift'] })
  for (let i = 0; i < 4; i += 1) await expect(checks.nth(i)).toBeChecked()
  await dialog.getByLabel('Select all SIN').uncheck()
  await dialog.getByLabel('Select all HND').uncheck()
  const handles = dialog.getByRole('button', { name: /Drag to select/ })
  const firstHandle = (await handles.nth(0).boundingBox())!
  const secondHandle = (await handles.nth(1).boundingBox())!
  await page.mouse.move(firstHandle.x + firstHandle.width / 2, firstHandle.y + firstHandle.height / 2)
  await page.mouse.down()
  await page.mouse.move(secondHandle.x + secondHandle.width / 2, secondHandle.y + secondHandle.height / 2, { steps: 8 })
  await page.mouse.up()
  await expect(checks.nth(0)).toBeChecked()
  await expect(checks.nth(1)).toBeChecked()
  await expect(checks.nth(2)).not.toBeChecked()
  await dialog.getByLabel('Select all SIN').uncheck()
  await dialog.getByLabel('Select all SIN').check()
  await dialog.getByLabel('Select all HND').check()
  await expect(dialog.getByText(/cards · 1 sheet/)).toBeVisible()
  await expect(dialog.getByAltText('Selected print PDF, sheet 1')).toBeVisible({ timeout: 30000 })
  const downloadPromise = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'Export selected PDF' }).click()
  const download = await downloadPromise
  const { PDFDocument } = await import('@cantoo/pdf-lib')
  const { readFile } = await import('node:fs/promises')
  const pdf = await PDFDocument.load(await readFile(await download.path()))
  expect(pdf.getPageCount()).toBe(1)
  const streams = pdf.getPages()[0]!.node.Contents() as unknown as PDFArray
  let printed = ''
  for (let index = 0; index < streams.size(); index += 1) {
    const stream = pdf.context.lookup(streams.get(index) as never) as { contents?: Uint8Array }
    if (!stream.contents) continue
    const unzip = new DecompressionStream('deflate')
    const writer = unzip.writable.getWriter()
    void writer.write(new Uint8Array(stream.contents)); void writer.close()
    printed += await new Response(unzip.readable).text()
  }
  expect(printed).toContain('53494E205349474E4154555245')
  expect(printed).toContain('484E44205349474E4154555245')
  await dialog.getByRole('button', { name: 'Close' }).click()
  const projectDownload = page.waitForEvent('download')
  await projectAction(page, 'Save project')
  const projectPath = await (await projectDownload).path()
  const saved = JSON.parse((await readFile(projectPath)).toString()) as { version: number; sources: Record<string, number>; images: string[]; pdfs: string[] }
  expect(saved.version).toBe(4)
  expect(Object.keys(saved.sources)).toHaveLength(2)
  expect(saved.pdfs).toHaveLength(1)
  expect(new Set(saved.images).size).toBe(saved.images.length)
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const fresh = await context.newPage()
  await fresh.goto('/')
  const open = fresh.waitForEvent('filechooser')
  await projectAction(fresh, 'Open project')
  await (await open).setFiles({ name: 'stations.crewbtc', mimeType: 'application/json', buffer: await readFile(projectPath) })
  await expect(fresh.getByRole('button', { name: 'HND', exact: true })).toBeVisible({ timeout: 30000 })
  await expect(textZones(fresh).first()).toContainText('HND SIGNATURE')
  await fresh.getByRole('button', { name: 'SIN', exact: true }).click()
  await expect(textZones(fresh).first()).toContainText('SIN SIGNATURE')
  await context.close()
})

test('new project clears all stations but preserves shared inspector settings', async ({ page }) => {
  await uploadPdf(page)
  await openSheetSettings(page)
  await page.getByLabel('Cell width').fill('60')
  await openFormatting(page)
  await page.getByLabel('crockeries keywords').fill('tray')
  page.once('dialog', (dialog) => dialog.accept('HND'))
  await page.getByRole('button', { name: 'New station' }).click()
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: /add pdfs/i }).first().click()
  await (await chooser).setFiles(pdfFile())
  await expect(textZones(page).first()).toBeVisible({ timeout: 30000 })
  page.once('dialog', (dialog) => dialog.dismiss())
  await projectAction(page, 'New project')
  await expect(textZones(page).first()).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept())
  await projectAction(page, 'New project')
  await expect(textZones(page)).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'HND', exact: true })).toHaveCount(0)
  await openSheetSettings(page)
  await expect(page.getByLabel('Cell width')).toHaveValue('60')
  await expect(page.getByLabel('crockeries keywords')).toHaveValue('tray')
  await page.waitForTimeout(900)
  await page.reload()
  await openFormatting(page)
  await expect(textZones(page)).toHaveCount(0)
  await openSheetSettings(page)
  await expect(page.getByLabel('Cell width')).toHaveValue('60')
})

test('different pages of one PDF can be assigned to different stations', async ({ page }) => {
  await uploadPdf(page)
  await page.getByRole('button', { name: 'Station 1', exact: true }).dblclick()
  await page.getByRole('textbox', { name: 'Rename Station 1' }).fill('SIN')
  await page.keyboard.press('Enter')
  page.once('dialog', (dialog) => dialog.accept('1'))
  await page.getByRole('button', { name: 'Choose pages for this station' }).click()
  await expect(page.getByText(/1 of \d+ pages in this station/)).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept('HND'))
  await page.getByRole('button', { name: 'New station' }).click()
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: /add pdfs/i }).first().click()
  await (await chooser).setFiles(pdfFile())
  await expect(page.getByRole('button', { name: 'Choose pages for this station' })).toBeVisible({ timeout: 30000 })
  page.once('dialog', (dialog) => dialog.accept('2'))
  await page.getByRole('button', { name: 'Choose pages for this station' }).click()
  await expect(page.getByLabel('Card corner label').first()).toHaveValue('HND')
  await page.getByRole('button', { name: 'Export PDF' }).click()
  await page.getByRole('menuitem', { name: 'Custom selection' }).click()
  const dialog = page.getByRole('dialog', { name: 'Print selection' })
  await dialog.getByLabel('Select all SIN').check()
  await dialog.getByLabel('Select all HND').check()
  await expect(dialog.getByText('2 cards · 1 sheet')).toBeVisible()
  await dialog.getByLabel('Select all HND').uncheck()
  await expect(dialog.getByText('1 card · 1 sheet')).toBeVisible()
  await dialog.locator('fieldset').filter({ hasText: 'HND' }).getByRole('checkbox').nth(1).check()
  await expect(dialog.getByText('2 cards · 1 sheet')).toBeVisible()
  await expect(dialog.getByAltText('Selected print PDF, sheet 1')).toBeVisible({ timeout: 30000 })
  await dialog.getByRole('button', { name: 'Close' }).click()
  await page.waitForTimeout(1000)
  await page.reload()
  await expect(page.getByText(/1 of \d+ pages in this station/)).toBeVisible({ timeout: 30000 })
  await page.getByRole('button', { name: 'SIN', exact: true }).click()
  await expect(page.getByText(/1 of \d+ pages in this station/)).toBeVisible()
})

test('project, station and print controls remain reachable at 1024 pixels', async ({ page }) => {
  await page.setViewportSize({ width: 1024, height: 768 })
  await uploadPdf(page)
  for (const name of ['New project', 'Open project', 'Save project', 'Export PDF', 'Preview PDF', 'Settings']) {
    const control = page.getByRole('button', { name, exact: true })
    await expect(control).toBeVisible()
    const box = await control.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(1024)
  }
})
