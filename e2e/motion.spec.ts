test('reduced motion makes tabs, menus, accordions and dialogs immediate', async ({ page }) => {
  const { uploadPdf } = await import('./fixtures')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await uploadPdf(page)
  await expect(page.locator('html')).toHaveAttribute('data-reduced-motion', 'true')
  const assertNoMotion = async (selector: string) => {
    const motion = await page.locator(selector).first().evaluate((element) => {
      const style = getComputedStyle(element)
      return { animation: style.animationName, transition: style.transitionProperty, scroll: style.scrollBehavior }
    })
    expect(motion).toEqual({ animation: 'none', transition: 'none', scroll: 'auto' })
  }
  page.once('dialog', (dialog) => dialog.accept('Second'))
  await page.getByRole('button', { name: 'New station' }).click()
  await page.getByRole('button', { name: 'Station 1', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Station 1', exact: true })).toHaveAttribute('aria-current', 'page')
  await assertNoMotion('[aria-label="Station workspaces"] button')
  await page.getByRole('button', { name: 'Export PDF' }).click()
  await assertNoMotion('[data-motion-popup]')
  await page.getByRole('menuitem', { name: 'Custom selection' }).click()
  const print = page.locator('dialog[aria-label="Print selection"]')
  await assertNoMotion('dialog[aria-label="Print selection"]')
  await print.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(print).toHaveCount(0)
  await expect(page.locator('.motion-backdrop-exit')).toHaveCount(0)
  const toggle = page.getByRole('button', { name: 'Toggle Automate formatting section' })
  const input = page.getByLabel('crockeries keywords')
  const firstFrame = async () => toggle.evaluate(async (button) => {
    const accordion = document.getElementById(button.getAttribute('aria-controls')!)!
    ;(button as HTMLElement).click()
    await new Promise<void>((resolve) => requestAnimationFrame(() => resolve()))
    const style = getComputedStyle(accordion)
    return { expanded: accordion.dataset.expanded, height: accordion.getBoundingClientRect().height, opacity: style.opacity, visibility: style.visibility, transition: style.transitionProperty }
  })
  const closed = await firstFrame()
  expect(closed).toMatchObject({ expanded: 'false', opacity: '0', visibility: 'hidden', transition: 'none' })
  expect(closed.height).toBe(0)
  const opened = await firstFrame()
  expect(opened).toMatchObject({ expanded: 'true', opacity: '1', visibility: 'visible', transition: 'none' })
  expect(opened.height).toBeGreaterThan(0)
  await expect(input).toBeVisible()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  const dialog = page.locator('dialog[aria-label="Settings"]')
  await assertNoMotion('dialog[aria-label="Settings"]')
  expect(await dialog.evaluate((el) => getComputedStyle(el, '::backdrop').animationName)).toBe('none')
  await page.getByRole('button', { name: 'Close settings' }).click()
  await expect(dialog).not.toHaveAttribute('data-motion-phase', 'exit')
  await expect(page.locator('.motion-backdrop-exit')).toHaveCount(0)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('switch', { name: 'Reduced motion' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-reduced-motion', 'false')
  expect(await page.locator('.inspector-accordion').first().evaluate((el) => getComputedStyle(el).transitionProperty)).toContain('grid-template-rows')
})
