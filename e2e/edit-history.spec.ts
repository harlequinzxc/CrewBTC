import { expect, test } from '@playwright/test'
import { openSheetSettings, textZones, uploadPdf } from './fixtures'

test('card edits undo and redo through keyboard and buttons, clearing redo on a new edit', async ({ page }) => {
  await uploadPdf(page)
  const body = textZones(page).nth(1)
  const original = await body.getAttribute('aria-label')
  await body.click()
  const editor = page.getByLabel('Edit card text')
  await editor.fill('first experiment')
  await page.keyboard.press('Escape')
  await expect(body).toHaveAttribute('aria-label', /first experiment/)
  await page.keyboard.press('ControlOrMeta+z')
  await expect(body).toHaveAttribute('aria-label', original!)
  await page.keyboard.press('ControlOrMeta+Shift+z')
  await expect(body).toHaveAttribute('aria-label', /first experiment/)
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect(body).toHaveAttribute('aria-label', original!)
  await page.keyboard.press('ControlOrMeta+y')
  await expect(body).toHaveAttribute('aria-label', /first experiment/)
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await body.click()
  await editor.fill('second experiment')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Redo edit' })).toBeDisabled()
})

test('native input undo remains native while formatting and automation use edit history', async ({ page }) => {
  await uploadPdf(page)
  const body = textZones(page).nth(1)
  await body.click()
  const editor = page.getByLabel('Edit card text')
  await editor.fill('plate')
  await editor.press('End')
  await editor.pressSequentially(' test')
  await page.keyboard.press('ControlOrMeta+z')
  await expect(editor).toHaveValue('plate tes')
  await editor.fill('plate')
  await page.getByRole('button', { name: 'CROCKERIES callout' }).click()
  await expect(page.getByRole('button', { name: 'CROCKERIES callout' })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await body.click()
  await expect(page.getByRole('button', { name: 'CROCKERIES callout' })).toHaveAttribute('aria-pressed', 'false')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Redo edit' }).click()
  await body.click()
  await expect(page.getByRole('button', { name: 'CROCKERIES callout' })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await page.getByLabel('crockeries keywords').fill('plate')
  page.once('dialog', (dialog) => void dialog.accept())
  await page.getByRole('button', { name: 'Automate formatting', exact: true }).click()
  await expect(body).toHaveAttribute('aria-label', /•/)
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect(body).not.toHaveAttribute('aria-label', /•/)
  await page.getByRole('button', { name: 'Redo edit' }).click()
  await expect(body).toHaveAttribute('aria-label', /•/)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(body).not.toHaveAttribute('aria-label', /•/)
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect(body).toHaveAttribute('aria-label', /•/)
})

test('sheet scale, dimensions and divider changes undo without crossing station boundaries', async ({ page }) => {
  await uploadPdf(page)
  await page.locator('[data-image]').first().click()
  const top = page.getByLabel('Top value')
  const original = await top.textContent()
  const box = (await page.locator('[data-divider="header"]').first().boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + 25, { steps: 6 })
  await page.mouse.up()
  await expect(top).not.toHaveText(original!)
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect(top).toHaveText(original!)
  await page.getByRole('button', { name: 'Redo edit' }).click()
  await expect(top).not.toHaveText(original!)
  await openSheetSettings(page)
  const width = page.getByLabel('Cell width')
  await width.fill('190')
  await width.press('Tab')
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect(width).toHaveValue('52')
  await page.getByRole('button', { name: 'Redo edit' }).click()
  await expect(width).toHaveValue('190')
  const size = page.getByLabel('All text size')
  await size.fill('120')
  await size.press('Tab')
  await page.getByRole('button', { name: 'Undo edit' }).click()
  await expect(size).toHaveValue('90')
  await page.getByRole('button', { name: 'Redo edit' }).click()
  await expect(size).toHaveValue('120')
  page.once('dialog', (dialog) => void dialog.accept('New station'))
  await page.getByRole('button', { name: 'New station' }).click()
  await expect(page.getByRole('button', { name: 'Undo edit' })).toBeDisabled()
})
