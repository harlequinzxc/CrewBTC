import { expect, test } from '@playwright/test'
import { textZones, uploadPdf } from './fixtures'

test('the live PDF preview updates while editing and closes without losing work', async ({ page }) => {
  await uploadPdf(page)
  const toggle = page.getByRole('button', { name: 'Preview PDF' })
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  const preview = page.getByRole('complementary', { name: 'PDF preview' })
  await expect(preview.getByText('PDF preview up to date')).toBeVisible({ timeout: 30_000 })
  const image = preview.getByRole('img', { name: 'Generated PDF, sheet 1' })
  await expect(image).toBeVisible()
  const before = await image.getAttribute('src')
  await preview.getByRole('button', { name: 'Zoom in PDF preview' }).click()
  await expect(preview.getByText('125%', { exact: true })).toBeVisible()
  await expect(image).toHaveCSS('width', /.+px/)
  await preview.getByRole('button', { name: 'Fit', exact: true }).click()
  await expect(preview.getByText('100%', { exact: true })).toBeVisible()
  await textZones(page).nth(1).click()
  await page.getByLabel('Edit card text').fill('LIVE PREVIEW UPDATED')
  await expect(preview.getByText('Updating PDF preview…')).toBeVisible()
  await expect(preview.getByText('PDF preview up to date')).toBeVisible({ timeout: 30_000 })
  await expect.poll(() => image.getAttribute('src')).not.toBe(before)
  await page.keyboard.press('Escape')
  await preview.getByRole('button', { name: 'Close PDF preview' }).click()
  await expect(preview).toHaveCount(0)
  await expect(toggle).toBeFocused()
  await expect(textZones(page).nth(1)).toContainText('LIVE PREVIEW UPDATED')
  await toggle.click()
  await expect(page.getByRole('complementary', { name: 'PDF preview' }).getByText('PDF preview up to date')).toBeVisible({ timeout: 30_000 })
})

test('the narrow overlay can be opened and closed without unmounting the workspace', async ({ page }) => {
  await page.setViewportSize({ width: 1024, height: 768 })
  await uploadPdf(page)
  const cells = await page.locator('[data-cell]').count()
  await page.getByRole('button', { name: 'Preview PDF' }).click()
  const preview = page.getByRole('complementary', { name: 'PDF preview' })
  await expect(preview.getByText('PDF preview up to date')).toBeVisible({ timeout: 30_000 })
  await preview.getByRole('button', { name: 'Close PDF preview' }).focus()
  await page.keyboard.press('Escape')
  await expect(preview).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Preview PDF' })).toBeFocused()
  await expect(page.locator('[data-cell]')).toHaveCount(cells)
})

test('preview navigation renders each actual sheet and does not silently show sheet one', async ({ page }) => {
  await uploadPdf(page)
  const width = page.getByLabel('Cell width')
  await width.fill('190')
  await width.press('Tab')
  const height = page.getByLabel('Cell height')
  await height.fill('200')
  await height.press('Tab')
  await expect(page.getByText('210 × 297 mm · 2 sheets')).toBeVisible()
  await page.getByRole('button', { name: 'Preview PDF' }).click()
  const preview = page.getByRole('complementary', { name: 'PDF preview' })
  await expect(preview.getByText('PDF preview up to date')).toBeVisible({ timeout: 30_000 })
  const first = await preview.getByRole('img', { name: 'Generated PDF, sheet 1' }).getAttribute('src')
  await preview.getByRole('button', { name: 'Next preview sheet' }).click()
  await expect(preview.getByText('PDF preview up to date')).toBeVisible({ timeout: 30_000 })
  const second = preview.getByRole('img', { name: 'Generated PDF, sheet 2' })
  await expect(second).toBeVisible()
  expect(await second.getAttribute('src')).not.toBe(first)
  await expect(preview.getByRole('button', { name: 'Next preview sheet' })).toBeDisabled()
  await preview.getByRole('button', { name: 'Previous preview sheet' }).click()
  await expect(preview.getByRole('img', { name: 'Generated PDF, sheet 1' })).toBeVisible({ timeout: 30_000 })
})
